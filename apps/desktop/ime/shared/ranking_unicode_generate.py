"""Regenerate Unicode 17 tables from the pinned source directory (no network)."""
import hashlib
import json
import pathlib
import sys

source = pathlib.Path(sys.argv[1])
target = pathlib.Path(__file__).parent
recorded = json.loads((target / 'ranking_unicode_sources.json').read_text(encoding='utf-8'))
if recorded['unicode_version'] != '17.0.0':
    raise ValueError('The generator implements the pinned Unicode 17 boundary rules.')
for name, provenance in recorded['sources'].items():
    if hashlib.sha256((source / name).read_bytes()).hexdigest() != provenance['sha256']:
        raise ValueError('Pinned Unicode source digest mismatch: ' + name)
flags = [0] * 0x110000
properties = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
              'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']


def rows(name):
    for line in (source / name).read_text(encoding='utf-8').splitlines():
        data = line.split('#')[0].strip()
        if not data:
            continue
        fields = [field.strip() for field in data.split(';')]
        span = fields[0].split('..')
        yield int(span[0], 16), int(span[-1], 16), fields[1:]


for start, end, fields in rows('GraphemeBreakProperty.txt'):
    for cp in range(start, end + 1):
        flags[cp] |= properties.index(fields[0])
for start, end, fields in rows('emoji-data.txt'):
    if fields[0] == 'Extended_Pictographic':
        for cp in range(start, end + 1):
            flags[cp] |= 16
for start, end, fields in rows('DerivedCoreProperties.txt'):
    if fields[0] == 'InCB':
        for cp in range(start, end + 1):
            flags[cp] |= {'Consonant': 32, 'Linker': 64, 'Extend': 96}[fields[1]]
# Keep existing macOS UTF-16 trailing-character policy: supplementary symbols
# were never removed by characterIsMember:. Grapheme segmentation is full UAX29.
for line in (source / 'UnicodeData.txt').read_text(encoding='utf-8').splitlines():
    fields = line.split(';')
    cp = int(fields[0], 16)
    if cp <= 0xffff and fields[2][0] in 'PS':
        flags[cp] |= 128
for start, end, fields in rows('PropList.txt'):
    if fields[0] == 'White_Space':
        for cp in range(start, min(end, 0xffff) + 1):
            flags[cp] |= 128
for start, end, fields in rows('Scripts.txt'):
    if fields[0] == 'Han':
        for cp in range(start, end + 1):
            flags[cp] |= 256
ranges = []
start = 0
for cp in range(1, len(flags) + 1):
    if cp == len(flags) or flags[cp] != flags[start]:
        if flags[start]:
            ranges.append((start, cp - 1, flags[start]))
        start = cp
header = '// Generated by ranking_unicode_generate.py; Unicode 17.0.0.\n'
header += '// See ranking_unicode_sources.json and ranking_unicode_LICENSE.txt.\n'
header += 'static constexpr UnicodeRange unicodeRanges[] = {\n'
header += ''.join('    {0x%x,0x%x,%d},\n' % item for item in ranges) + '};\n'
(target / 'ranking_unicode_data.h').write_text(header, encoding='utf-8', newline='\n')
names = ['GraphemeBreakProperty.txt', 'emoji-data.txt', 'DerivedCoreProperties.txt',
         'PropList.txt', 'UnicodeData.txt', 'Scripts.txt', 'GraphemeBreakTest.txt', 'license.txt']
manifest = {'unicode_version': '17.0.0', 'sources': {}}
for name in names:
    subdir = 'auxiliary/' if name.startswith('Grapheme') else 'emoji/' if name == 'emoji-data.txt' else ''
    url = 'https://www.unicode.org/license.txt' if name == 'license.txt' else 'https://www.unicode.org/Public/17.0.0/ucd/' + subdir + name
    manifest['sources'][name] = {'url': url, 'sha256': hashlib.sha256((source / name).read_bytes()).hexdigest()}
(target / 'ranking_unicode_sources.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
(target / 'ranking_unicode_LICENSE.txt').write_bytes((source / 'license.txt').read_bytes())
corpus = target.parents[3] / 'benchmarks/corpora/ime-learning-v1'
corpus.mkdir(parents=True, exist_ok=True)
(corpus / 'GraphemeBreakTest-17.0.0.txt').write_bytes((source / 'GraphemeBreakTest.txt').read_bytes())
(corpus / 'Scripts-17.0.0.txt').write_bytes((source / 'Scripts.txt').read_bytes())
