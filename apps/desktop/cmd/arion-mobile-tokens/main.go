// Command arion-mobile-tokens writes Sunbeam's tokens for the iOS and Android
// apps from the Sunbeam MyGo package that the desktop pins, so every Arion
// client follows one design source. With -check it fails when a written file
// differs from what the pinned package produces.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"unicode"

	"github.com/AstraFoundry/design/packages/mygo/sunbeam"
	"github.com/egoist/mygo/ui"
)

type color struct {
	name        string
	light, dark ui.Color
}

type scalar struct {
	name  string
	value float32
}

type tokens struct {
	colors    []color
	substrate []color
	radii     []scalar
	spaces    []scalar
	shadows   []shadowToken
}

type shadowToken struct {
	name        string
	light, dark []sunbeam.Shadow
}

var colorType = reflect.TypeOf(ui.Color{})
var shadowType = reflect.TypeOf([]sunbeam.Shadow{})

func collect() tokens {
	var t tokens
	light := reflect.ValueOf(sunbeam.Light()).Elem()
	dark := reflect.ValueOf(sunbeam.Dark()).Elem()
	fields := light.Type()
	for i := 0; i < fields.NumField(); i++ {
		f := fields.Field(i)
		if strings.HasPrefix(f.Name, "Art") {
			continue // Illustration tokens; the mobile apps draw no art stages.
		}
		switch f.Type {
		case colorType:
			t.colors = append(t.colors, color{
				name:  lowerFirst(f.Name),
				light: light.Field(i).Interface().(ui.Color),
				dark:  dark.Field(i).Interface().(ui.Color),
			})
		case shadowType:
			t.shadows = append(t.shadows, shadowToken{
				name:  lowerFirst(f.Name),
				light: light.Field(i).Interface().([]sunbeam.Shadow),
				dark:  dark.Field(i).Interface().([]sunbeam.Shadow),
			})
		}
	}
	// The substrate scale is mode-invariant: the dictation pill and keyboard
	// recording surface use it in both appearances, as the desktop pill does.
	for _, s := range []struct {
		name string
		c    ui.Color
	}{
		{"substrate", sunbeam.Substrate},
		{"substrateSurface", sunbeam.SubstrateSurface},
		{"substrateRaised", sunbeam.SubstrateRaised},
		{"substrateLine", sunbeam.SubstrateLine},
		{"substrateEdge", sunbeam.SubstrateEdge},
		{"substrateHi", sunbeam.SubstrateHi},
		{"substrateInk", sunbeam.SubstrateInk},
		{"substrateMuted", sunbeam.SubstrateMuted},
	} {
		t.substrate = append(t.substrate, color{name: s.name, light: s.c, dark: s.c})
	}
	t.radii = []scalar{
		{"xs", sunbeam.RadiusXS}, {"sm", sunbeam.RadiusSM}, {"md", sunbeam.RadiusMD},
		{"lg", sunbeam.RadiusLG}, {"xl", sunbeam.RadiusXL}, {"xl2", sunbeam.Radius2XL},
		{"chip", sunbeam.RadiusChip}, {"focus", sunbeam.RadiusFocus}, {"xl3", sunbeam.Radius3XL},
		{"tile", sunbeam.RadiusTile}, {"stage", sunbeam.RadiusStage},
	}
	t.spaces = []scalar{
		{"unit", sunbeam.SpaceUnit}, {"hairline", sunbeam.SpaceHairline},
		{"tileInset", sunbeam.SpaceTileInset}, {"cardInsetSm", sunbeam.SpaceCardInsetSM},
		{"cardInsetMd", sunbeam.SpaceCardInsetMD}, {"cardInsetLg", sunbeam.SpaceCardInsetLG},
	}
	return t
}

func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func num(v float32) string {
	s := fmt.Sprintf("%g", v)
	if !strings.ContainsAny(s, ".e") {
		s += ".0"
	}
	return s
}

const header = "Code generated by apps/desktop/cmd/arion-mobile-tokens from the pinned Sunbeam MyGo package. DO NOT EDIT."

func swift(t tokens) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n// swiftlint:disable all\n\n", header)
	b.WriteString("/// An sRGB color with 8-bit channels, as Sunbeam defines it.\npublic struct SunbeamRGBA: Equatable, Sendable {\n    public let r: UInt8, g: UInt8, b: UInt8, a: UInt8\n}\n\n")
	b.WriteString("/// One layer of a CSS box-shadow.\npublic struct SunbeamShadow: Equatable, Sendable {\n    public let x: Double, y: Double, blur: Double, spread: Double\n    public let color: SunbeamRGBA\n    public let inset: Bool\n}\n\n")
	b.WriteString("/// A Sunbeam color token with its light and dark values.\npublic struct SunbeamColorToken: Equatable, Sendable {\n    public let light: SunbeamRGBA\n    public let dark: SunbeamRGBA\n}\n\n")
	b.WriteString("/// A Sunbeam shadow token with its light and dark layers.\npublic struct SunbeamShadowToken: Equatable, Sendable {\n    public let light: [SunbeamShadow]\n    public let dark: [SunbeamShadow]\n}\n\n")
	rgba := func(c ui.Color) string {
		return fmt.Sprintf("SunbeamRGBA(r: %d, g: %d, b: %d, a: %d)", c.R, c.G, c.B, c.A)
	}
	shadows := func(list []sunbeam.Shadow) string {
		parts := make([]string, len(list))
		for i, s := range list {
			parts[i] = fmt.Sprintf("SunbeamShadow(x: %s, y: %s, blur: %s, spread: %s, color: %s, inset: %t)", num(s.X), num(s.Y), num(s.Blur), num(s.Spread), rgba(s.Color), s.Inset)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}
	b.WriteString("public enum SunbeamTokens {\n")
	b.WriteString("    public enum Color {\n")
	for _, c := range append(append([]color{}, t.colors...), t.substrate...) {
		fmt.Fprintf(&b, "        public static let %s = SunbeamColorToken(light: %s, dark: %s)\n", c.name, rgba(c.light), rgba(c.dark))
	}
	b.WriteString("    }\n\n    public enum Shadow {\n")
	for _, s := range t.shadows {
		fmt.Fprintf(&b, "        public static let %s = SunbeamShadowToken(light: %s, dark: %s)\n", s.name, shadows(s.light), shadows(s.dark))
	}
	b.WriteString("    }\n\n    public enum Radius {\n")
	for _, r := range t.radii {
		fmt.Fprintf(&b, "        public static let %s: Double = %s\n", r.name, num(r.value))
	}
	b.WriteString("    }\n\n    public enum Space {\n")
	for _, s := range t.spaces {
		fmt.Fprintf(&b, "        public static let %s: Double = %s\n", s.name, num(s.value))
	}
	b.WriteString("    }\n}\n")
	return b.Bytes()
}

func kotlin(t tokens) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\npackage si.astrafoundry.arion.design\n\n", header)
	b.WriteString("/** An sRGB color as 0xAARRGGBB. */\n@JvmInline\nvalue class SunbeamArgb(val value: Long)\n\n")
	b.WriteString("/** One layer of a CSS box-shadow, in dp. */\ndata class SunbeamShadow(val x: Float, val y: Float, val blur: Float, val spread: Float, val color: SunbeamArgb, val inset: Boolean)\n\n")
	b.WriteString("/** A Sunbeam color token with its light and dark values. */\ndata class SunbeamColorToken(val light: SunbeamArgb, val dark: SunbeamArgb)\n\n")
	b.WriteString("/** A Sunbeam shadow token with its light and dark layers. */\ndata class SunbeamShadowToken(val light: List<SunbeamShadow>, val dark: List<SunbeamShadow>)\n\n")
	argb := func(c ui.Color) string {
		return fmt.Sprintf("SunbeamArgb(0x%02X%02X%02X%02X)", c.A, c.R, c.G, c.B)
	}
	f := func(v float32) string { return num(v) + "f" }
	shadows := func(list []sunbeam.Shadow) string {
		parts := make([]string, len(list))
		for i, s := range list {
			parts[i] = fmt.Sprintf("SunbeamShadow(%s, %s, %s, %s, %s, %t)", f(s.X), f(s.Y), f(s.Blur), f(s.Spread), argb(s.Color), s.Inset)
		}
		return "listOf(" + strings.Join(parts, ", ") + ")"
	}
	b.WriteString("object SunbeamTokens {\n    object Color {\n")
	for _, c := range append(append([]color{}, t.colors...), t.substrate...) {
		fmt.Fprintf(&b, "        val %s = SunbeamColorToken(%s, %s)\n", c.name, argb(c.light), argb(c.dark))
	}
	b.WriteString("    }\n\n    object Shadow {\n")
	for _, s := range t.shadows {
		fmt.Fprintf(&b, "        val %s = SunbeamShadowToken(%s, %s)\n", s.name, shadows(s.light), shadows(s.dark))
	}
	b.WriteString("    }\n\n    /** Corner radii in dp. */\n    object Radius {\n")
	for _, r := range t.radii {
		fmt.Fprintf(&b, "        const val %s = %s\n", r.name, f(r.value))
	}
	b.WriteString("    }\n\n    /** Spacing in dp. */\n    object Space {\n")
	for _, s := range t.spaces {
		fmt.Fprintf(&b, "        const val %s = %s\n", s.name, f(s.value))
	}
	b.WriteString("    }\n}\n")
	return b.Bytes()
}

func main() {
	root := flag.String("root", "../..", "repository root")
	check := flag.Bool("check", false, "fail when a generated file is out of date")
	flag.Parse()
	t := collect()
	outputs := map[string][]byte{
		"apps/ios/ArionKit/Sources/ArionKit/Design/SunbeamTokens.swift":                     swift(t),
		"apps/android/design/src/main/kotlin/si/astrafoundry/arion/design/SunbeamTokens.kt": kotlin(t),
	}
	stale := false
	for rel, want := range outputs {
		path := filepath.Join(*root, rel)
		if *check {
			got, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(got, want) {
				fmt.Fprintf(os.Stderr, "%s is out of date; run pnpm mobile:tokens\n", rel)
				stale = true
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if stale {
		os.Exit(1)
	}
}
