import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'benchmarks/reproduction/llm-ime-alignment-v1');
const op = process.argv[2];
let args;
if (['prepare', 'run', 'report'].includes(op)) args = ['-B', path.join(dir, 'study.py'), op, ...process.argv.slice(3)];
else if (['test', 'verify', 'archive'].includes(op)) args = ['-B', path.join(dir, op === 'test' ? 'test_report.py' : `${op}.py`), ...process.argv.slice(3)];
else throw new Error('Use prepare, run, report, test, verify or archive');
const result = spawnSync(process.env.EVAL_PYTHON || 'python3', args, { cwd: root, shell: false, stdio: 'inherit' });
if (result.error) throw result.error;
process.exitCode = result.status ?? 1;
