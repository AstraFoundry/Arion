// Writes the iOS and Android string catalogs from packages/mobile-strings,
// the one source of the mobile apps' user-facing copy. With --check it fails
// when a written file differs from the catalog.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const source = path.join(root, 'packages/mobile-strings/strings.json');
const catalog = JSON.parse(await readFile(source, 'utf8'));
const languages = ['en', 'zh-Hans'];
const header = 'Generated by scripts/generate-mobile-strings.mjs from packages/mobile-strings/strings.json. Do not edit.';
const errors = [];

const keys = Object.keys(catalog.strings).sort();
// iosSettings.* is the copy of Arion's page in the iOS Settings app; it goes
// only to the app's Settings.bundle, in this order.
const settingsKeys = ['iosSettings.setup', 'iosSettings.missingKeyboards'];
const androidKeys = keys.filter(key => !key.startsWith('iosSettings.'));
// The iOS app draws the same note in its setup preview, so iOS keeps these keys.
const appKeys = keys;
for (const key of keys) {
  if (!/^[a-z][a-zA-Z0-9]*(\.[a-z][a-zA-Z0-9]*)+$/.test(key)) errors.push(`${key}: keys are dotted lowerCamel segments`);
  const entry = catalog.strings[key];
  const names = languages.map(language => {
    if (typeof entry[language] !== 'string' || !entry[language].trim()) errors.push(`${key}: missing ${language}`);
    return [...(entry[language] ?? '').matchAll(/\{([a-z][a-zA-Z0-9]*)\}/g)].map(match => match[1]);
  });
  if (names[0].join() !== [...new Set(names[0])].join()) errors.push(`${key}: a placeholder repeats`);
  if ([...names[0]].sort().join() !== [...names[1]].sort().join()) errors.push(`${key}: placeholders differ between languages`);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const placeholders = key => [...catalog.strings[key].en.matchAll(/\{([a-z][a-zA-Z0-9]*)\}/g)].map(match => match[1]);
// Placeholders are numbered by their order in English, so a translation may
// reorder them.
function positional(key, language, marker) {
  const order = placeholders(key);
  return catalog.strings[key][language]
    .replace(/%/g, '%%')
    .replace(/\{([a-z][a-zA-Z0-9]*)\}/g, (_, name) => `%${order.indexOf(name) + 1}$${marker}`);
}
const identifier = key => key.split('.').map((part, index) => index ? part[0].toUpperCase() + part.slice(1) : part).join('');
// baseURLPlaceholder -> base_url_placeholder: an acronym ends before a capitalized word.
const androidName = key => key.replace(/\./g, '_').replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();

function xcstrings() {
  const strings = {};
  for (const key of appKeys) {
    const localizations = {};
    for (const language of languages) {
      localizations[language] = { stringUnit: { state: 'translated', value: placeholders(key).length ? positional(key, language, '@') : catalog.strings[key][language] } };
    }
    strings[key] = { extractionState: 'manual', localizations };
    if (catalog.strings[key].comment) strings[key].comment = catalog.strings[key].comment;
  }
  return JSON.stringify({ sourceLanguage: 'en', strings, version: '1.0' }, null, 2) + '\n';
}

function swift() {
  const lines = [`// ${header}`, '', 'import Foundation', '', '/// The localized copy of the Arion app and keyboard.', 'public enum L10n {'];
  for (const key of appKeys) {
    const args = placeholders(key);
    if (args.length) {
      const params = args.map(name => `${name}: String`).join(', ');
      lines.push(`    public static func ${identifier(key)}(${params}) -> String { format("${key}", ${args.join(', ')}) }`);
    } else {
      lines.push(`    public static var ${identifier(key)}: String { lookup("${key}") }`);
    }
  }
  lines.push('', '    private static func lookup(_ key: String) -> String {', '        Bundle.module.localizedString(forKey: key, value: nil, table: nil)', '    }', '');
  lines.push('    private static func format(_ key: String, _ args: CVarArg...) -> String {', '        String(format: lookup(key), locale: Locale.current, arguments: args)', '    }', '}', '');
  return lines.join('\n');
}

function escapeAndroid(value) {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/^@/, '\\@').replace(/^\?/, '\\?');
}

function androidStrings(language) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${header} -->`, '<resources>'];
  for (const key of androidKeys) {
    const formatted = placeholders(key).length > 0;
    const value = formatted ? positional(key, language, 's') : catalog.strings[key][language];
    lines.push(`    <string name="${androidName(key)}"${formatted ? '' : ' formatted="false"'}>${escapeAndroid(value)}</string>`);
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

// Settings.bundle: one group per note, its text a footer looked up in Root.strings.
function settingsPlist() {
  const groups = settingsKeys.map(key => [
    '\t\t<dict>',
    '\t\t\t<key>FooterText</key>',
    `\t\t\t<string>${key}</string>`,
    '\t\t\t<key>Type</key>',
    '\t\t\t<string>PSGroupSpecifier</string>',
    '\t\t</dict>',
  ].join('\n'));
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<!-- ${header} -->`,
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    '\t<key>PreferenceSpecifiers</key>',
    '\t<array>',
    ...groups,
    '\t</array>',
    '\t<key>StringsTable</key>',
    '\t<string>Root</string>',
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

function settingsStrings(language) {
  const escape = value => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
  return [`/* ${header} */`, '', ...settingsKeys.map(key => `"${key}" = "${escape(catalog.strings[key][language])}";`), ''].join('\n');
}

const missing = settingsKeys.filter(key => !catalog.strings[key]);
const unlisted = keys.filter(key => key.startsWith('iosSettings.') && !settingsKeys.includes(key));
if (missing.length || unlisted.length) {
  console.error(`Settings.bundle keys: missing ${missing.join(', ') || 'none'}, unlisted ${unlisted.join(', ') || 'none'}`);
  process.exit(1);
}

const outputs = new Map([
  ['apps/ios/Arion/Settings.bundle/Root.plist', settingsPlist()],
  ['apps/ios/Arion/Settings.bundle/en.lproj/Root.strings', settingsStrings('en')],
  ['apps/ios/Arion/Settings.bundle/zh-Hans.lproj/Root.strings', settingsStrings('zh-Hans')],
  ['apps/ios/ArionKit/Sources/ArionKit/Resources/Localizable.xcstrings', xcstrings()],
  ['apps/ios/ArionKit/Sources/ArionKit/Localization/L10n.swift', swift()],
  ['apps/android/design/src/main/res/values/strings.xml', androidStrings('en')],
  ['apps/android/design/src/main/res/values-zh-rCN/strings.xml', androidStrings('zh-Hans')],
]);

let stale = false;
for (const [relative, text] of outputs) {
  const file = path.join(root, relative);
  if (check) {
    let current = null;
    try { current = await readFile(file, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current !== text) {
      console.error(`${relative} is out of date; run pnpm mobile:generate`);
      stale = true;
    }
    continue;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, text);
}
if (stale) process.exit(1);
