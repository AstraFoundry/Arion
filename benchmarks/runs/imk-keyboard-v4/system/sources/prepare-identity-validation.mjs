import {execFileSync} from 'node:child_process';
import {existsSync,mkdirSync,readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {macosSigningSettings,prepareMacOSSigning,stripAppleCredentials} from '../../../scripts/lib/desktop-signing.mjs';
const root=process.cwd();
const run=path.join(root,'.workspace/e2e/imk-system/run-09');
if(existsSync(run))throw new Error('Identity validation output already exists');
mkdirSync(run,{recursive:true});
if(existsSync('.env'))process.loadEnvFile('.env');
const settings=macosSigningSettings(process.env);
if(!settings)throw new Error('Configured signing is required');
const signing=prepareMacOSSigning(settings);
const env=stripAppleCredentials(process.env);delete env.MYGO_UPDATER_PRIVATE_KEY;
const execute=(command,args)=>execFileSync(command,args,{cwd:root,env,encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
const source=path.join(root,'apps/desktop/build/darwin-arm64/Arion.app/Contents/Resources/ArionInput.app');
const bundle=path.join(run,'payload/ArionInput.app');
const parentID='si.astrafoundry.inputmethod.arion.validation';
const modeID=parentID+'.pinyin';
const hash=file=>createHash('sha256').update(readFileSync(file)).digest('hex');
try {
 mkdirSync(path.dirname(bundle),{recursive:true});execute('ditto',[source,bundle]);
 const metadata=path.join(bundle,'Contents/Info.plist');
 const info=JSON.parse(execute('plutil',['-convert','json','-o','-',metadata]));
 const originalParent=info.CFBundleIdentifier, originalMode=info.ComponentInputModeDict.tsVisibleInputModeOrderedArrayKey[0];
 const mode=info.ComponentInputModeDict.tsInputModeListKey[originalMode];
 info.CFBundleIdentifier=parentID;mode.TISInputSourceID=modeID;
 info.ComponentInputModeDict.tsInputModeListKey={[modeID]:mode};info.ComponentInputModeDict.tsVisibleInputModeOrderedArrayKey=[modeID];
 writeFileSync(metadata,JSON.stringify(info));execute('plutil',['-convert','xml1',metadata]);
 for(const language of ['en','zh-Hans']){
  const file=path.join(bundle,'Contents/Resources',language+'.lproj/InfoPlist.strings');
  const content=readFileSync(file,'utf8');if(!content.includes(originalMode))throw new Error('Expected input-mode localization absent');
  writeFileSync(file,content.replaceAll(originalMode,modeID));
 }
 const manifest={schemaVersion:1,parentID,modeID,originalParent,originalMode,changes:['CFBundleIdentifier','child mode identifier/key/order','localized mode identifier keys','code signature'],unchangedConnection:info.InputMethodConnectionName,sourceExecutableSHA256:hash(path.join(source,'Contents/MacOS/ArionInput')),engineSHA256:hash(path.join(source,'Contents/Frameworks/librime.1.dylib'))};
 execute('codesign',['--force','--options','runtime','--timestamp','--sign',settings.identity,bundle]);
 execute('codesign',['--verify','--deep','--strict',bundle]);
 if(hash(path.join(bundle,'Contents/Frameworks/librime.1.dylib'))!==manifest.engineSHA256)throw new Error('Engine unexpectedly changed');
 manifest.executableSHA256=hash(path.join(bundle,'Contents/MacOS/ArionInput'));manifest.infoSHA256=hash(metadata);
 writeFileSync(path.join(run,'artifact.json'),JSON.stringify(manifest,null,2)+'\n');
 const zip=path.join(run,'Arion-identity-validation.zip');execute('ditto',['-c','-k','--keepParent',bundle,zip]);
 const args=['notarytool','submit',zip,'--keychain-profile',settings.profile,'--wait','--timeout','10m','--output-format','json'];
 if(settings.keychain)args.push('--keychain',settings.keychain);
 const submission=JSON.parse(execute('xcrun',args));
 writeFileSync(path.join(run,'notarization.json'),JSON.stringify(submission,null,2)+'\n');
 if(submission.status!=='Accepted')throw new Error('Identity validation notarization not accepted');
 execute('xcrun',['stapler','staple',bundle]);
 const assessment=execFileSync('spctl',['--assess','--type','execute','--verbose=2',bundle],{env,encoding:'utf8',stdio:['ignore','pipe','pipe']});
 writeFileSync(path.join(run,'gatekeeper.txt'),assessment);
 console.log(JSON.stringify({ready:true,parentID,modeID,notarization:submission.status}));
} finally {signing.cleanup();}
