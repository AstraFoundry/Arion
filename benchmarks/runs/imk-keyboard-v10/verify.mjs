import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const base=new URL('./',import.meta.url);
const manifest=JSON.parse(readFileSync(new URL('manifest.json',base),'utf8'));
for(const [name,expected] of Object.entries(manifest.files))assert.equal(createHash('sha256').update(readFileSync(new URL(name,base))).digest('hex'),expected,name);
const report=JSON.parse(readFileSync(new URL('controls/visibility-control-summary.json',base),'utf8'));
assert.equal(report.install.state,1);
assert.equal(report.developmentHostRestoredByteForByte,true);
assert.equal(report.settingsSearchEmpty,true);
assert.equal(report.settingsProcessRestarted,true);
assert.equal(report.sourceSelectionAttempted,false);
assert.equal(report.hostLaunchAttempted,false);
assert.equal(report.cause,'unresolved');
assert.equal(report.firstControlSourceBeforeRestore.own.find(s=>s.id==='si.astrafoundry.inputmethod.arion').enabled,false);
const parent=report.sourceBeforeRestore.own.find(s=>s.id==='si.astrafoundry.inputmethod.arion');
if(parent)assert.equal(parent.enabled,false);
assert(report.sourceBeforeRestore.own.every(s=>!s.selected));
const ui=readFileSync(new URL('controls/signed-fresh-settings-ui.txt',base),'utf8');
assert(ui.includes('Value: Arion'));
assert(!/^.*row.*Arion.*$/m.test(ui));
console.log(`PASS: ${Object.keys(manifest.files).length} hashes; original UI/install outputs and derived limits retained; signed/fresh-Settings visibility failure, exact bundle restoration and no selection/host launch.`);
